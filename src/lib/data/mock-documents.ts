/**
 * Helper untuk query produk hukum dari dataset
 */
export function getAllLegalDocuments(): LegalDocumentItem[] {
  return LEGAL_DOCUMENTS;
}

export function getLegalDocumentBySlug(slug: string): LegalDocumentItem | undefined {
  return LEGAL_DOCUMENTS.find((d) => d.slug === slug);
}

export function getLegalDocumentByParams(
  typeSlug: string,
  yearStr: string,
  seqStr: string
): LegalDocumentItem | undefined {
  const year = parseInt(yearStr, 10);
  const seq = parseInt(seqStr, 10);
  return LEGAL_DOCUMENTS.find(
    (d) =>
      d.typeSlug.toLowerCase() === typeSlug.toLowerCase() &&
      d.year === year &&
      d.sequenceNumber === seq
  );
}

export function getLegalDocumentsByType(typeSlug: string): LegalDocumentItem[] {
  return LEGAL_DOCUMENTS.filter(
    (d) => d.typeSlug.toLowerCase() === typeSlug.toLowerCase()
  );
}
